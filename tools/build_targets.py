"""Generate targets.yaml from discovery/results.json.

For each employer, the best working candidate found by tools/discover.py
becomes its target. Employers without a working candidate are written as
disabled entries with the reason, so they show up in the README coverage
table. Entries listed in tools/overrides.yaml win over discovery results
(use it for manual fixes and flags such as internship_in_description).

    python tools/build_targets.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tracker import company_score  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

HEADER = """\
# Employers scraped every day. Generated by tools/build_targets.py from the
# discovery results, then merged with tools/overrides.yaml. Edit overrides.yaml
# (not this file) for manual changes, or add an entry by hand at the end.
#
#   name          display name
#   type          kind of employer (french_bank, intl_bank, european_bank, broker,
#                 asset_manager, hedge_fund, commodities, infrastructure, software,
#                 insurance, institution, consulting)
#   platform      adapter in tracker/adapters/ (greenhouse, lever, workday, oracle, ...)
#   careers_url   public careers page, shown in the interface and in error reports
#   params        adapter-specific settings (see the docstring of each adapter)
#   enabled       false = skipped (see notes for the reason)
#   notes         free text
"""


JSON_PLATFORMS = {"workday", "oracle", "greenhouse", "lever", "smartrecruiters", "ashby",
                  "teamtailor", "workable", "recruitee", "eightfold"}


def reason(result: dict) -> str:
    tests = result.get("tests", [])
    if any(t["status"] == "robots" for t in tests):
        return "robots.txt disallows automated access to its job search"
    if any(t["status"] == "error" for t in tests):
        errs = "; ".join(t["error"][:80] for t in tests if t["status"] == "error")
        return f"candidate platforms failed ({errs})"
    if result.get("signatures"):
        sigs = ", ".join(k for k in result["signatures"] if k != "jsonld")
        if sigs:
            return f"uses {sigs}, which has no public job API supported yet"
    errors = result.get("page_errors") or []
    if any("403" in e for e in errors):
        return "careers site blocks automated requests (HTTP 403)"
    if any("RobotsDisallowed" in e for e in errors):
        return "robots.txt disallows automated access to the careers pages"
    if errors:
        return "careers site not reachable by a script (" + errors[0][:80] + ")"
    return "in-house careers site with no machine-readable job list found"


def update_readme(employers: list[dict]) -> None:
    """Rewrite the coverage section of the README from targets.yaml."""
    on = [e for e in employers if e.get("enabled", True)]
    off = [e for e in employers if not e.get("enabled", True)]
    lines = [f"{len(on)} of {len(employers)} employers are scraped daily.", "",
             "| Employer | Platform |", "|---|---|"]
    lines += [f"| {e['name']} | {e['platform']} |" for e in sorted(on, key=lambda e: e["name"].lower())]
    lines += ["", "**Not covered yet**, with the reason:", "", "| Employer | Reason |", "|---|---|"]
    lines += [f"| {e['name']} | {e.get('notes', '')} |" for e in sorted(off, key=lambda e: e["name"].lower())]
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- coverage:start -->", "<!-- coverage:end -->"
    head, rest = text.split(start, 1)
    tail = rest.split(end, 1)[1]
    readme.write_text(f"{head}{start}\n" + "\n".join(lines) + f"\n{end}{tail}", encoding="utf-8")


def write_site_list(employers: list[dict]) -> None:
    """docs/employers.json: every employer, for the "Entreprises" tab of the site."""
    rows = []
    for e in employers:
        points, reasons = company_score.score(e["name"], e["type"])
        rows.append({"name": e["name"], "type": e["type"], "careers_url": e["careers_url"],
                     "covered": e.get("enabled", True), "notes": e.get("notes", ""),
                     "priority": points, "reasons": reasons})
    rows.sort(key=lambda r: r["name"].lower())
    (ROOT / "docs" / "employers.json").write_text(
        json.dumps(rows, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def main() -> int:
    results = json.loads((ROOT / "discovery" / "results.json").read_text(encoding="utf-8"))
    overrides_file = ROOT / "tools" / "overrides.yaml"
    overrides = {}
    if overrides_file.exists():
        for entry in (yaml.safe_load(overrides_file.read_text(encoding="utf-8")) or {}).get("employers", []):
            overrides[entry["name"]] = entry

    employers = []
    for r in results:
        best = r.get("best")
        # JSON platforms answering correctly are kept even with no internship
        # today; HTML parsers returning nothing may simply not match the page.
        if best and (best["fetched"] > 0 or best["platform"] in JSON_PLATFORMS):
            entry = {"name": r["name"], "type": r["type"], "platform": best["platform"],
                     "careers_url": r["careers_url"], "params": best["params"]}
        else:
            entry = {"name": r["name"], "type": r["type"], "platform": "generic",
                     "careers_url": r["careers_url"], "params": {"urls": [r["careers_url"]]},
                     "enabled": False, "notes": reason(r)}
        if r["name"] in overrides:
            entry.update(overrides.pop(r["name"]))
        employers.append(entry)
    employers.extend(overrides.values())  # manual entries not in discovery

    body = yaml.safe_dump({"employers": employers}, allow_unicode=True, sort_keys=False, width=120)
    (ROOT / "targets.yaml").write_text(HEADER + "\n" + body, encoding="utf-8")
    enabled = sum(1 for e in employers if e.get("enabled", True))
    update_readme(employers)
    write_site_list(employers)
    print(f"{enabled}/{len(employers)} employers enabled")
    return 0


if __name__ == "__main__":
    sys.exit(main())
